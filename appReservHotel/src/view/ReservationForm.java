    public void loadCombos() {
       IdClientComboBox.removeAllItems();
       IdChambreComboBox.removeAllItems();

        for (Client c : cc.getAll()) {
           IdClientComboBox.addItem(c);
        }

        for (Chambre ch : chc.getAll()) {
           IdChambreComboBox.addItem(ch);
        }
}

    public void loadReservation() {
    model.setRowCount(0);

    for (Reservation r : rc.getAll()) {
        model.addRow(new Object[]{
            r.getId(),
            r.getClientId(),
            r.getChambreId(),
            r.getDateDebut(),
            r.getDateFin()
        });
    }
}

