    private void reserverBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_reserverBtnActionPerformed
        
        try {
        Chambre ch = (Chambre) IdChambreComboBox.getSelectedItem();
        Client cl = (Client) IdClientComboBox.getSelectedItem();

        if (ch == null || cl == null || dateDebut.getDate() == null || dateFin.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Remplissez tous les champs");
            return;
        }

        LocalDate debut = dateDebut.getDate().toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();

        LocalDate fin = dateFin.getDate().toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();

        rc.reserver(ch.getId(), cl.getId(), debut, fin);

        JOptionPane.showMessageDialog(this, "Réservation ajoutée");
        loadReservation();

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage());
    }
        
           
               
    }//GEN-LAST:event_reserverBtnActionPerformed

    private void supprimerBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_supprimerBtnActionPerformed
        int ligne = ResvTab.getSelectedRow();

        if (ligne == -1) {
           JOptionPane.showMessageDialog(this, "Sélectionnez une réservation");
           return;
        }

        int id = Integer.parseInt(ResvTab.getValueAt(ligne, 0).toString());

        int rep = JOptionPane.showConfirmDialog(this, "Voulez-vous supprimer ?", "Confirmation",JOptionPane.YES_NO_OPTION);

    if (rep == JOptionPane.YES_OPTION) {
        Reservation r = new Reservation();
        r.setId(id);
        rc.delete(r);

        loadReservation();
    }
    }//GEN-LAST:event_supprimerBtnActionPerformed

