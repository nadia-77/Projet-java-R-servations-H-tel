    private void modifierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_modifierActionPerformed
        try {
            int selectedRow = tableChambre.getSelectedRow();
            if(selectedRow == -1) {
                JOptionPane.showMessageDialog(null, "Sélectionnez une ligne pour modifier");
                return;
            }

            int id = Integer.parseInt(tableChambre.getValueAt(selectedRow, 0).toString());

            int numero = Integer.parseInt(txtNumero.getText());
            String type = txtType.getText();
            double prix = Double.parseDouble(txtPrix.getText());
            
            Chambre c = new Chambre();
            c.setId(id);
            c.setNumero(numero);
            c.setType(type);
            c.setPrixParNuit(prix);

            chc.update(c);

            loadChambre();
            clearForm();

            JOptionPane.showMessageDialog(null, "Chambre modifiée avec succès !");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Veuillez entrer des données valides");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Erreur: " + e.getMessage());
        }
    }//GEN-LAST:event_modifierActionPerformed

    private void ajouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ajouterActionPerformed

     try {
        int numero = Integer.parseInt(txtNumero.getText());
        String type = txtType.getText();
        double prix = Double.parseDouble(txtPrix.getText());

        Chambre c = new Chambre(numero, type, prix);
        chc.ajouter(c);

        loadChambre();
        clearForm();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "les données que vous avez entrée est incorrect ");
    }
    }//GEN-LAST:event_ajouterActionPerformed

    private void supprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_supprimerActionPerformed
        int ligne = tableChambre.getSelectedRow();
        if (ligne >= 0) {
            int id = (int) model.getValueAt(ligne, 0);
            int reponse = JOptionPane.showConfirmDialog(null, "Voulez-vous supprimer ?", "Confirmation", JOptionPane.YES_NO_OPTION);
            if (reponse == JOptionPane.YES_OPTION) {
                Chambre c = new Chambre(); 
                c.setId(id);
                new ChambreController(null).delete(c);
                loadChambre();
            }
        } else {
            JOptionPane.showMessageDialog(null, "Sélectionnez une chambre !");
        }


    }//GEN-LAST:event_supprimerActionPerformed
