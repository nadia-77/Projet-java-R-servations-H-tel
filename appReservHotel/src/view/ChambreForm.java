    public void loadChambre(){
        model.setRowCount(0);
        for (Chambre ch : chc.getAll()) {
           model.addRow(new Object[]{
            ch.getId(),
            ch.getNumero(),
            ch.getType(),
            ch.getPrixParNuit()
            });
        
        }
    }
    
